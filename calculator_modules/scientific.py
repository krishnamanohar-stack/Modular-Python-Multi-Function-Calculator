import math

def power(a,b):
    return math.pow(a,b)

def square_root(a):
    return math.sqrt(a)

def cube_root(a):
    return math.cbrt(a)

def percentage(percentage,value):
    return (percentage/100)*value

def factorial(n):
    return math.factorial(n)

def absolute(n):
    return abs(n)

def exponential(n):
    return math.exp(n)

def logarithm(n):
    return math.log(n)

def log10(n):
    return math.log10(n)

def sin(degree):
    radians = math.radians(degree)
    return math.sin(radians)

def cos(degree):
    radians = math.radians(degree)
    return round(math.cos(radians),10)


def tan(degree):
    radians = math.radians(degree)
    return math.tan(radians)


